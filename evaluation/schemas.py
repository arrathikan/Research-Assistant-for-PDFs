"""Pydantic schemas for Ragas RAG evaluation and benchmark datasets.

Implements data structures specified in AGENTS.md Rule 4 and Rule 8.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


class EvaluationSample(BaseModel):
    """Schema for a single evaluated question-answering trace."""

    sample_id: str = Field(..., description="Unique identifier for the benchmark item")
    user_question: str = Field(..., description="Query posed to the research assistant")
    retrieved_contexts: List[str] = Field(default_factory=list, description="List of chunk texts provided as context")
    generated_answer: str = Field(..., description="Response generated by the LLM")
    reference_answer: Optional[str] = Field(default=None, description="Ground truth answer if available")
    retrieved_chunk_ids: List[str] = Field(default_factory=list, description="IDs of chunks retrieved")
    source_page_numbers: List[int] = Field(default_factory=list, description="PDF page numbers cited")
    model_configuration: Dict[str, Any] = Field(default_factory=dict, description="Model, temperature, retriever parameters")
    is_answerable: bool = Field(default=True, description="Whether the question can be answered from the paper")
    created_at: datetime = Field(default_factory=_utc_now)


class EvaluationReportSummary(BaseModel):
    """Summary of scores computed across an evaluation run."""

    run_id: str = Field(..., description="Unique run identifier")
    timestamp: datetime = Field(default_factory=_utc_now)
    total_samples: int = Field(...)
    retrieval_strategy: str = Field(..., description="e.g. hybrid_rrf or semantic_only")
    faithfulness_score: Optional[float] = None
    answer_relevancy_score: Optional[float] = None
    context_precision_score: Optional[float] = None
    context_recall_score: Optional[float] = None
    factual_correctness_score: Optional[float] = None
    notes: Optional[str] = None
