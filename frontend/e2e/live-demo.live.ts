import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { expect as baseExpect, test } from '@playwright/test';
import type { ChatResponse } from '../src/types/chat';

const expect = baseExpect.configure({ timeout: 30_000 });

// Explicit, paid, public-paper check. Never selected by the default suite or CI.
test('public benchmark: real upload dedup, summary, chat and PDF citations', async ({ page, request }, testInfo) => {
  test.setTimeout(180_000);
  const pdf = process.env.RESEARCHAI_QA_PDF;
  const id = process.env.RESEARCHAI_QA_DOCUMENT_ID;
  if (!pdf || !id || !/^[0-9a-f]{24}$/.test(id)) throw new Error('Set QA PDF path and document ID for the reviewed public benchmark.');
  expect(createHash('sha256').update(readFileSync(pdf)).digest('hex')).toBe('f37f6fabe0fe0d8c73b67579cd115dbf14e282cfb7b7af655ae8109638402c9b');
  const base = 'http://127.0.0.1:8000';
  const status = async () => {
    const response = await request.get(`${base}/api/v1/documents/${id}/processing`);
    expect(response.ok()).toBeTruthy();
    return response.json() as Promise<{ status: string; generation: number }>;
  };
  const before = await status();
  expect(before.status).toBe('COMPLETED');
  let pdfLoads = 0;
  let duplicate = false;
  const responses: ChatResponse[] = [];
  const pageErrors: string[] = [];
  page.on('pageerror', error => pageErrors.push(error.message));
  page.on('request', value => { if (new URL(value.url()).pathname.endsWith('/pdf')) pdfLoads++; });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('/');
  await page.getByRole('navigation', { name: 'Main Navigation' }).getByRole('button', { name: 'Upload Paper', exact: true }).click();
  await page.getByTestId('main-upload-trigger').click();
  await page.getByTestId('file-input').setInputFiles(pdf);
  const uploadPromise = page.waitForResponse(value => new URL(value.url()).pathname === '/api/v1/documents' && value.request().method() === 'POST');
  await page.getByRole('button', { name: 'Upload paper', exact: true }).click();
  const uploaded = await uploadPromise;
  expect(uploaded.ok()).toBeTruthy();
  const body = await uploaded.json();
  duplicate = body.is_duplicate === true && body.document.id === id;
  await page.getByRole('button', { name: 'Open Workspace', exact: true }).click();
  expect(duplicate).toBeTruthy();
  await expect(page.getByRole('heading', { name: 'Lost in the Middle: How Language Models Use Long Contexts' })).toBeVisible();
  await expect(page.getByTestId('pdf-viewer-panel')).toHaveCount(0);
  const shots = process.env.RESEARCHAI_QA_SCREENSHOTS;
  if (shots) await page.screenshot({ path: `${shots}/live-summary-1440.png` });
  await page.getByRole('tab', { name: 'AI Chatbot' }).click();
  await page.getByRole('textbox', { name: 'Question', exact: true }).fill('How many NaturalQuestions queries were used in the multi-document QA setup, and what answer type was selected?');
  const chatPromise = page.waitForResponse(value => new URL(value.url()).pathname.endsWith('/chat') && value.request().method() === 'POST');
  await page.getByRole('button', { name: 'Send Message' }).click();
  const chat = await chatPromise;
  expect(chat.ok()).toBeTruthy();
  responses.push(await chat.json() as ChatResponse);
  await expect.poll(() => responses.length, { timeout: 120_000 }).toBe(1);
  const answer = responses[0];
  expect(answer.document_id).toBe(id);
  expect(answer.answer).toMatch(/2,?655/);
  expect(answer.citations.length).toBeGreaterThan(0);
  expect(answer.citations.every(source => source.document_id === id && source.page_number >= 1 && source.page_number <= 17)).toBeTruthy();
  await page.getByRole('textbox', { name: 'Question', exact: true }).fill('Preserve this draft');
  const first = answer.citations[0];
  await page.getByRole('button', { name: `Open citation 1, page ${first.page_number}` }).click();
  const number = page.getByRole('spinbutton', { name: 'PDF page number' });
  await expect(number).toHaveValue(String(first.page_number));
  await expect(page.locator('canvas')).toBeVisible();
  await expect(page.locator('.react-pdf__Page__textContent')).toBeVisible();
  if (shots) await page.screenshot({ path: `${shots}/live-chat-citation-1440.png` });
  const loads = pdfLoads;
  await page.getByRole('button', { name: 'Close PDF', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Question', exact: true })).toHaveValue('Preserve this draft');
  await expect(page.getByRole('log')).toContainText(/2,?655/);
  await page.setViewportSize({ width: 375, height: 900 });
  await page.getByRole('button', { name: 'View Original PDF', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Original PDF' })).toBeVisible();
  await expect(number).toHaveValue(String(first.page_number));
  if (shots) await page.screenshot({ path: `${shots}/live-pdf-375.png` });
  await page.getByRole('button', { name: 'Close PDF', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Question', exact: true })).toHaveValue('Preserve this draft');
  expect(pdfLoads).toBe(loads);
  expect(await status()).toEqual(before);
  expect(pageErrors).toEqual([]);
  await testInfo.attach('live-checks', { body: JSON.stringify({ duplicate, jobUnchanged: true, pdfLoads, answer, pageErrors }), contentType: 'application/json' });
});
